  // ── Core i18n engine ──

  /**
   * Get translation for a given key and language.
   * Falls back to English if key not found in target language.
   */
  function getTranslation(lang, key) {
    var dict = translations[lang];
    if (dict && dict[key] !== undefined) return dict[key];
    return translations.en[key] || null;
  }

  /**
   * Apply all translations to elements with data-i18n attribute.
   * Also handles data-i18n-placeholder for input placeholders.
   */
  function applyTranslations(lang) {
    var elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(function (el) {
      var key = el.getAttribute('data-i18n');
      var text = getTranslation(lang, key);
      if (text !== null) {
        el.textContent = text;
      }
    });

    // Handle placeholders
    var placeholders = document.querySelectorAll('[data-i18n-placeholder]');
    placeholders.forEach(function (el) {
      var key = el.getAttribute('data-i18n-placeholder');
      var text = getTranslation(lang, key);
      if (text !== null) {
        el.placeholder = text;
      }
    });

    // Handle HTML lang attribute
    document.documentElement.lang = lang;

    // Handle RTL for Arabic
    if (lang === 'ar') {
      document.documentElement.dir = 'rtl';
    } else {
      document.documentElement.dir = 'ltr';
    }
  }

  /**
   * Set and persist language, then apply translations.
   */
  function setLanguage(lang) {
    lang = lang.toLowerCase();
    if (!translations[lang]) lang = 'en';
    localStorage.setItem(LANG_KEY, lang);
    applyTranslations(lang);
    return lang;
  }

  /**
   * Get the current language from localStorage or default to 'en'.
   */
  function getCurrentLang() {
    var saved = localStorage.getItem(LANG_KEY);
    if (saved && translations[saved]) return saved;
    return 'en';
  }

  // ── Initialize on DOM ready ──
  function init() {
    var lang = getCurrentLang();
    applyTranslations(lang);

    // Sync trigger text with saved language
    var triggerText = document.querySelector('.lang-trigger__text');
    if (triggerText) {
      triggerText.textContent = lang.toUpperCase();
    }

    // Mark the correct option as active
    var options = document.querySelectorAll('.lang-option');
    options.forEach(function (opt) {
      opt.classList.remove('active');
      if (opt.dataset.code && opt.dataset.code.toLowerCase() === lang) {
        opt.classList.add('active');
      }
    });
  }

  // Apply on load (before main.js runs its cosmetic handler)
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }

  // Expose setLanguage globally for the language selector in main.js
  window.FitQuestI18n = {
    setLanguage: setLanguage,
    getCurrentLang: getCurrentLang,
    getTranslation: getTranslation,
  };

